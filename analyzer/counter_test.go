package analyzer

import (
	"strings"
	"testing"
)

func TestCountSkips(t *testing.T) {
	_, cands := detectionKey("a.go", "")
	if _, _, _, _, ok := count("a.go", cands, []byte("// Code generated by x. DO NOT EDIT.\npackage a\n")); ok {
		t.Error("generated file should be skipped")
	}
	_, cands = detectionKey("a.js", "")
	if _, _, _, _, ok := count("a.js", cands, []byte(strings.Repeat("var a=1;", 200)+"\n")); ok {
		t.Error("minified file should be skipped")
	}
	if _, _, _, _, ok := count("a.js", cands, []byte("var a = 1;\n")); !ok {
		t.Error("plain file should be counted")
	}
	key, cands := detectionKey("script", "")
	if key == "" {
		t.Fatal("extensionless file should be a shebang candidate")
	}
	if lang, code, _, _, ok := count("script", cands, []byte("#!/usr/bin/env python3\nprint(1)\n")); !ok || lang != "Python" || code != 1 {
		t.Errorf("shebang: lang=%q code=%d ok=%v", lang, code, ok)
	}
	if _, _, _, _, ok := count("LICENSE", cands, []byte("MIT\n")); ok {
		t.Error("unknown extensionless file should be skipped")
	}
	if key, _ := detectionKey("x.inc", "go"); key != "=Go" {
		t.Errorf("override key = %q", key)
	}
	if key, _ := detectionKey("photo.png", ""); key != "" {
		t.Errorf("png key = %q", key)
	}
}
