package analyzer

import (
	"path"
	"strings"
	"sync"

	"github.com/boyter/scc/v3/processor"
)

var sccOnce sync.Once

// sccInit configures scc's package level state once. After this point scc's
// globals are only read (LanguageFeatures is additionally guarded by scc's own
// mutex), so CountStats is safe to call concurrently on different FileJobs.
func sccInit() {
	sccOnce.Do(func() {
		processor.Minified = true
		processor.Generated = true
		processor.GeneratedMarkers = []string{"do not edit", "<auto-generated />"}
		processor.ProcessConstants()
	})
}

// sccLanguages maps lowercase scc language names to their canonical names,
// used to resolve linguist-language overrides.
var (
	sccLanguagesOnce sync.Once
	sccLanguages     map[string]string
)

func resolveLanguage(name string) (string, bool) {
	sccInit()
	sccLanguagesOnce.Do(func() {
		sccLanguages = map[string]string{}
		processor.LanguageFeaturesMutex.Lock()
		for k := range processor.LanguageFeatures {
			sccLanguages[strings.ToLower(k)] = k
		}
		processor.LanguageFeaturesMutex.Unlock()
	})
	l, ok := sccLanguages[strings.ToLower(name)]
	return l, ok
}

// detectionKey returns the candidate languages for a path (by file name
// only), joined as a string usable as part of the cache key. "" means scc
// does not know this kind of file and it can be skipped without reading it.
func detectionKey(p, override string) (key string, candidates []string) {
	sccInit()
	if override != "" {
		if l, ok := resolveLanguage(override); ok {
			return "=" + l, []string{l}
		}
	}
	langs, _ := processor.DetectLanguage(path.Base(p))
	if len(langs) == 0 {
		return "", nil
	}
	return strings.Join(langs, ","), langs
}

// count runs scc over a blob. ok=false means the file must not be counted
// (binary, minified, generated, unknown shebang...).
func count(p string, candidates []string, content []byte) (lang string, code, comments, blanks int64, ok bool) {
	sccInit()
	if len(candidates) == 0 {
		return "", 0, 0, 0, false
	}
	name := path.Base(p)
	lang = processor.DetermineLanguage(name, candidates[0], candidates, content)
	if lang == processor.SheBang {
		head := content
		if len(head) > 200 {
			head = head[:200]
		}
		l, err := processor.DetectSheBang(string(head))
		if err != nil {
			return "", 0, 0, 0, false
		}
		lang = l
	}

	job := &processor.FileJob{
		Language: lang,
		Filename: name,
		Location: p,
		Content:  content,
		Bytes:    int64(len(content)),
	}
	processor.CountStats(job)
	if job.Binary || job.Minified || job.Generated {
		return "", 0, 0, 0, false
	}
	return lang, job.Code, job.Comment, job.Blank, true
}
